package script

import (
	"bytes"
	_ "embed"
	"fmt"
	"go/parser"
	"go/token"
	"strconv"
	"text/template"
)

const (
	moduleDefault    = "gorn.local/app"
	defaultGoVersion = "1.26"
)

//go:embed mod.gotmpl
var modTemplate string

var modTmpl = template.Must(template.New("mod").Option("missingkey=error").Parse(modTemplate))

var preamblePackages = []struct{ Path, Symbol string }{
	{"path/filepath", "filepath.Separator"},
	{"fmt", "fmt.Println"},
	{"os", "os.Stdout"},
	{"github.com/gornkit/gorn/sh", "sh.PreambleSentinel"},
	{"strconv", "strconv.IntSize"},
	{"strings", "strings.Contains"},
	{"time", "time.Nanosecond"},
}

// Generated contains a Go main file and a go.mod. MainGenerated preserves user
// formatting; only inserted code is formatted by the generator.
type Generated struct {
	MainGenerated []byte
	ModGenerated  []byte
}

// GenerateError wraps a generation error. Raw is populated only when internal
// generated source fails syntax validation, not for errors in the input source.
type GenerateError struct {
	Err error
	Raw []byte
}

func (e *GenerateError) Error() string { return e.Err.Error() }
func (e *GenerateError) Unwrap() error { return e.Err }

func Generate(f *File) (*Generated, error) {
	if f.UsePreamble {
		if err := checkPreambleConflicts(f); err != nil {
			return nil, err
		}
	}
	modData := struct {
		Module, GoVersion string
		Requires          []Require
	}{Module: f.Module, GoVersion: f.GoVersion, Requires: f.Requires}
	if modData.Module == "" {
		modData.Module = moduleDefault
	}
	if modData.GoVersion == "" {
		modData.GoVersion = defaultGoVersion
	}
	var mod bytes.Buffer
	if err := modTmpl.Execute(&mod, &modData); err != nil {
		return nil, err
	}

	var main bytes.Buffer
	fmt.Fprintf(&main, "// Code generated by gorn from %s; DO NOT EDIT.\n\n", f.SourcePath)
	writeSourceAnchor(&main, f.sourceName, 1, 1)
	if !f.UsePreamble {
		main.Write(f.Content)
	} else {
		end := f.packageEnd()
		main.Write(f.Content[:end])
		main.WriteString("\n//line gorn-generated:1:1\nimport (\n")
		for _, pkg := range preamblePackages {
			fmt.Fprintf(&main, "\t%q\n", pkg.Path)
		}
		main.WriteString(")\n")
		pos := f.fset.Position(f.fset.File(f.syntax.Pos()).Pos(end))
		writeSourceAnchor(&main, pos.Filename, pos.Line, pos.Column)
		main.Write(f.Content[end:])
		main.WriteString("\n//line gorn-generated:1:1\nvar (\n")
		for _, pkg := range preamblePackages {
			fmt.Fprintf(&main, "\t_ = %s\n", pkg.Symbol)
		}
		main.WriteString(")\n")
	}
	generated := main.Bytes()
	if _, err := parser.ParseFile(token.NewFileSet(), "main.gorn.go", generated, parser.SkipObjectResolution); err != nil {
		return nil, &GenerateError{Err: err, Raw: generated}
	}
	return &Generated{MainGenerated: generated, ModGenerated: mod.Bytes()}, nil
}

func writeSourceAnchor(out *bytes.Buffer, path string, line, column int) {
	if column == 0 {
		fmt.Fprintf(out, "//line %s:%d\n", path, line)
		return
	}
	fmt.Fprintf(out, "//line %s:%d:%d\n", path, line, column)
}

func checkPreambleConflicts(f *File) error {
	for _, imp := range f.syntax.Imports {
		path, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			continue
		}
		for _, pkg := range preamblePackages {
			if path == pkg.Path {
				return &GenerateError{Err: lineError(f.position(imp.Pos()).Line, fmt.Errorf("%w: %s", ErrPreambleImportConflict, path))}
			}
		}
	}
	return nil
}
